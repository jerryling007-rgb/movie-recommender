def get_db():
    db = sqlite3.connect(DB_PATH)
    db.row_factory = sqlite3.Row
    return db


def import_wogg_data():
    """将 wogg.net 数据导入数据库"""
    db = get_db()
    
    # Ensure categories exist
    for slug, name in WOGG_SLUG_MAP.items():
        existing = db.execute("SELECT id FROM categories WHERE slug=?", (slug,)).fetchone()
        if not existing:
            db.execute("INSERT INTO categories (name, slug, url_path) VALUES (?,?,?)",
                       (WOGG_CATEGORY_MAP[slug], slug, ""))
    
    # Ensure documentary category
    doc = db.execute("SELECT id FROM categories WHERE slug='documentary'").fetchone()
    if not doc:
        db.execute("INSERT INTO categories (name, slug, url_path) VALUES (?,?,?)",
                   ("纪录片", "documentary", ""))
    
    # Load category IDs
    cat_ids = {}
    for slug in WOGG_SLUG_MAP:
        row = db.execute("SELECT id FROM categories WHERE slug=?", (slug,)).fetchone()
        cat_ids[slug] = row["id"] if row else None
    
    # Also map rrdynb categories for merge
    rr_cats = {}
    for slug in ["movie", "tv", "anime", "variety", "short_drama"]:
        row = db.execute("SELECT id FROM categories WHERE slug=?", (slug,)).fetchone()
        rr_cats[slug] = row["id"] if row else None
    
    db.commit()
    
    imported = 0
    skipped = 0
    merged = 0
    
    for cat_slug, items in WOGG_DATA.items():
        cat_id = cat_ids.get(cat_slug)
        rr_cat_id = rr_cats.get(cat_slug)
        
        if not cat_id:
            print(f"  ⚠️ Category '{cat_slug}' not found, skipping")
            continue
        
        for title, vod_id, page in items:
            # Deduplicate: remove version suffixes for matching
            clean_title = re.sub(r'\s*[（(][^)）]*[)）]\s*$', '', title).strip()
            clean_title = re.sub(r'\s*(第[一二三四五六七八九十\d]+[季季]|第[一二三四五六七八九十\d]+部).*', '', clean_title).strip()
            
            # Check if already exists by title or source_id
            source_id = f"wogg_{vod_id}"
            existing = db.execute(
                "SELECT id FROM movies WHERE source_id=? OR title=?",
                (source_id, title)
            ).fetchone()
            
            if existing:
                # Update wogg data
                db.execute(
                    "UPDATE movies SET source_id=COALESCE(NULLIF(source_id,''),?), detail_url=?, updated_at=CURRENT_TIMESTAMP WHERE id=?",
                    (source_id, f"https://www.wogg.net/voddetail/{vod_id}.html", existing["id"])
                )
                merged += 1
                continue
            
            # Clean title
            title_clean = title.strip()
            
            # Insert new movie
            try:
                db.execute("""
                    INSERT INTO movies (title, category_id, sub_category, detail_url, source_id, 
                                       year, is_active, douban_rating, created_at, updated_at)
                    VALUES (?, ?, 'wogg', ?, ?, 2025, 1, 0, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)
                """, (
                    title_clean,
                    rr_cat_id or cat_id,  # prefer rrdynb category for merging
                    f"https://www.wogg.net/voddetail/{vod_id}.html",
                    source_id,
                ))
                imported += 1
            except Exception as e:
                skipped += 1
    
    db.commit()
    db.close()
    
    print(f"📊 wogg.net 导入结果: 新增 {imported}, 合并 {merged}, 跳过 {skipped}")


if __name__ == "__main__":
    import_wogg_data()
